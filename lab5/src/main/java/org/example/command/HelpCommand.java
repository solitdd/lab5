package org.example.command;

public class HelpCommand implements Command{


    @Override
    public void invoke(String params) {
        System.out.println("help : вывести справку по доступным командам\n" +
                "info : вывести в стандартный поток вывода информацию о коллекции (тип, дата инициализации, количество элементов и т.д.)\n" +
                "show : вывести в стандартный поток вывода все элементы коллекции в строковом представлении\n" +
                "add {element} : добавить новый элемент в коллекцию\n" +
                "update id {element} : обновить значение элемента коллекции, id которого равен заданному\n" +
                "remove_by_id id : удалить элемент из коллекции по его id\n" +
                "clear : очистить коллекцию\n" +
                "save : сохранить коллекцию в файл\n" +
                "execute_script file_name : считать и исполнить скрипт из указанного файла. В скрипте содержатся команды в таком же виде, в котором их вводит пользователь в интерактивном режиме.\n" +
                "exit : завершить программу (без сохранения в файл)\n" +
                "add_if_min {element} : добавить новый элемент в коллекцию, если его значение меньше, чем у наименьшего элемента этой коллекции\n" +
                "remove_greater {element} : удалить из коллекции все элементы, превышающие заданный\n" +
                "remove_lower {element} : удалить из коллекции все элементы, меньшие, чем заданный\n" +
                "remove_all_by_part_number partNumber : удалить из коллекции все элементы, значение поля partNumber которого эквивалентно заданному\n" +
                "count_greater_than_unit_of_measure unitOfMeasure : вывести количество элементов, значение поля unitOfMeasure которых больше заданного\n" +
                "filter_less_than_manufacturer manufacturer : вывести элементы, значение поля manufacturer которых меньше заданного");

    }

    @Override
    public String commandName() {
        return "help";
    }
}
